/* ======================== Low-Level SPI Functions ======================== */

/**
 * @brief  Perform one 16-bit SPI transfer.
 * @param  tx 16-bit word to transmit.
 * @retval 16-bit word received.
 */
static uint16_t adc_xfer(uint16_t tx)
{
    uint16_t rx = 0;

    CS_LOW();
    HAL_SPI_TransmitReceive(&hspi1, (uint8_t *)&tx, (uint8_t *)&rx, 1, HAL_MAX_DELAY);
    CS_HIGH();

    /* Inter-frame gap required by the AD7328 (~3 us at 480 MHz) */
    for (volatile int i = 0; i < 30; i++)
    {
        ;
    }

    return rx;
}

/**
 * @brief  Write to an AD7328 register, discarding the readback.
 */
static inline void adc_write(uint16_t w)
{
    (void)adc_xfer(w);
}

/* ======================== AD7328 Initialisation ======================== */

/**
 * @brief  Bring the AD7328 up in 0-10 V unipolar mode on all 8 channels.
 * @note   Write order matters: the control register must be written before
 *         the two range registers, otherwise the part keeps its default
 *         +/-10 V bipolar span and every reading sits near mid-scale.
 */
static void ad7328_init(void)
{
    char msg[100];

    HAL_UART_Transmit(&huart3, (uint8_t *)"\r\n=== AD7328 Init ===\r\n", 22, 100);

    /* Step 1: control register (straight binary coding, internal reference) */
    uint16_t ctrl = AD7328_WRITE | AD7328_CODING | AD7328_REF;
    snprintf(msg, sizeof(msg), "1. Control: 0x%04X\r\n", ctrl);
    HAL_UART_Transmit(&huart3, (uint8_t *)msg, strlen(msg), 100);
    adc_write(ctrl);
    HAL_Delay(1);

    /* Step 2: range register 1 (CH0-3) */
    snprintf(msg, sizeof(msg), "2. Range1:  0x%04X\r\n", RANGE1_ALL_0_10V);
    HAL_UART_Transmit(&huart3, (uint8_t *)msg, strlen(msg), 100);
    adc_write(RANGE1_ALL_0_10V);

    /* Step 3: range register 2 (CH4-7) */
    snprintf(msg, sizeof(msg), "3. Range2:  0x%04X\r\n", RANGE2_ALL_0_10V);
    HAL_UART_Transmit(&huart3, (uint8_t *)msg, strlen(msg), 100);
    adc_write(RANGE2_ALL_0_10V);

    /* Step 4: dummy write to latch the new configuration */
    snprintf(msg, sizeof(msg), "4. Activate: 0x%04X\r\n", AD7328_WRITE);
    HAL_UART_Transmit(&huart3, (uint8_t *)msg, strlen(msg), 100);
    (void)adc_xfer(AD7328_WRITE);

    HAL_UART_Transmit(&huart3, (uint8_t *)"===================\r\n\r\n", 23, 100);
}

/* ======================== AD7328 Reading ======================== */

/**
 * @brief  Read a single channel without using the on-chip sequencer.
 * @param  ch Channel number (0-7).
 * @retval 12-bit ADC code.
 */
static uint16_t adc_read(uint8_t ch)
{
    /* Control word: WRITE | channel select | coding | reference */
    uint16_t ctrl = AD7328_WRITE | (ch << 10) | AD7328_CODING | AD7328_REF;

    /* Start a conversion on the selected channel */
    CS_LOW();
    HAL_SPI_Transmit(&hspi1, (uint8_t *)&ctrl, 1, HAL_MAX_DELAY);
    CS_HIGH();

    /* Conversion time (~3 us) */
    for (volatile int i = 0; i < 30; i++)
    {
        ;
    }

    uint16_t raw = adc_xfer(0);

    /* Strip the channel-ID bits, keep the 12-bit result */
    return raw & 0x0FFF;
}

/**
 * @brief  Detect that the ADC has dropped its configured span.
 * @param  code0 Reading from channel 0, which is tied to a known-low node.
 * @retval true if the part appears to have reverted to its default range.
 */
static inline bool span_lost(uint16_t code0)
{
    return code0 > 150;
}

/**
 * @brief  Convert a 12-bit code to volts on the 0-10 V span.
 */
static inline float code_to_volts(uint16_t code)
{
    return (10.0f / 4096.0f) * (float)code;
}

/* ======================== Main Program ======================== */

int main(void)
{
#if defined(DUAL_CORE_BOOT_SYNC_SEQUENCE)
    int32_t timeout;
    timeout = 0xFFFF;
    while ((__HAL_RCC_GET_FLAG(RCC_FLAG_D2CKRDY) != RESET) && (timeout-- > 0))
    {
        ;
    }
    if (timeout < 0)
    {
        Error_Handler();
    }
#endif

    HAL_Init();
    SystemClock_Config();

#if defined(DUAL_CORE_BOOT_SYNC_SEQUENCE)
    __HAL_RCC_HSEM_CLK_ENABLE();
    HAL_HSEM_FastTake(HSEM_ID_0);
    HAL_HSEM_Release(HSEM_ID_0, 0);
    timeout = 0xFFFF;
    while ((__HAL_RCC_GET_FLAG(RCC_FLAG_D2CKRDY) == RESET) && (timeout-- > 0))
    {
        ;
    }
    if (timeout < 0)
    {
        Error_Handler();
    }
#endif

    /* Initialise peripherals */
    MX_GPIO_Init();
    MX_SPI1_Init();
    MX_TIM1_Init();
    MX_USART3_UART_Init();

    /* Start complementary PWM on TIM1 CH2 / CH2N */
    HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_2);
    HAL_TIMEx_PWMN_Start(&htim1, TIM_CHANNEL_2);

    /* Banner */
    HAL_Delay(200);
    char startup[] = "\r\n\r\n"
                     "==============================\r\n"
                     "  AD7328 - Individual Channel\r\n"
                     "  0-10V Unipolar Mode\r\n"
                     "==============================\r\n";
    HAL_UART_Transmit(&huart3, (uint8_t *)startup, strlen(startup), 200);

    /* Bring up the external ADC */
    CS_HIGH();
    HAL_Delay(100);
    ad7328_init();

    /* Main loop: sweep all 8 channels and stream them to the host */
    uint32_t loop_count = 0;
    while (1)
    {
        char line[100];

        /* Read channel 0 first and use it as the span-loss canary */
        uint16_t code0 = adc_read(0);
        if (span_lost(code0))
        {
            HAL_UART_Transmit(&huart3, (uint8_t *)"\r\n[RE-INIT AFTER BROWN-OUT]\r\n", 29, 100);
            ad7328_init();
            code0 = adc_read(0);
        }

        HAL_UART_Transmit(&huart3, (uint8_t *)"\r\n--- Readings ---\r\n", 19, 100);

        for (uint8_t ch = 0; ch < 8; ch++)
        {
            uint16_t code = (ch == 0) ? code0 : adc_read(ch);
            float volts = code_to_volts(code);

            snprintf(line, sizeof(line), "CH%u: code=%4u  V=%6.3f\r\n", ch, code, volts);
            HAL_UART_Transmit(&huart3, (uint8_t *)line, strlen(line), 100);
        }

        HAL_UART_Transmit(&huart3, (uint8_t *)"----------------\r\n", 18, 100);

        /* Heartbeat LED every 10 sweeps */
        if (++loop_count % 10 == 0)
        {
            HAL_GPIO_TogglePin(GPIOB, GPIO_PIN_14);
        }

        HAL_Delay(500);
    }
}

