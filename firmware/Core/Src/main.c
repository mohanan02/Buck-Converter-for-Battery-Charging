/* ===== GPIO Helpers ===== */
static inline void CS_LOW(void)
{
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_RESET);
}

static inline void CS_HIGH(void)
{
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_SET);
}

/* ===== AD7328 Register Bits ===== */
#define AD7328_WRITE    (1u << 15)
#define AD7328_RS1      (1u << 14)
#define AD7328_RS2      (1u << 13)

/* Control register bits */
#define AD7328_CODING   (1u << 5)   /* 1 = straight binary   */
#define AD7328_REF      (1u << 4)   /* 1 = internal reference */

/* Range register values for 0-10 V (bits = 11 for each channel) */
#define RANGE1_ALL_0_10V  (AD7328_WRITE | AD7328_RS1 | 0xFE0)  /* 0xBFE0 */
#define RANGE2_ALL_0_10V  (AD7328_WRITE | AD7328_RS2 | 0xFE0)  /* 0xDFE0 */

/* Peripheral handles */
SPI_HandleTypeDef hspi1;
TIM_HandleTypeDef htim1;
UART_HandleTypeDef huart3;

/* Function prototypes */
